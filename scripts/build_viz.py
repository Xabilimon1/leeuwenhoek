"""Regenerate viz/data.js, the numbers behind the local page viz/index.html.

Run after any change to the models, the design or the mechanisms, then reload
the page. Every figure the page prints comes from here (the page itself only
runs the forward pass for the input you pick).

Usage: uv run python scripts/build_viz.py
"""

import json
import subprocess
import time
from datetime import datetime
from pathlib import Path

import numpy as np

from leeuwenhoek.design import designed_weights, read_off
from leeuwenhoek.estimate import error_of_cone
from leeuwenhoek.exact import exact_accuracy
from leeuwenhoek.forward import forward
from leeuwenhoek.mechanisms import mechanism_cones
from leeuwenhoek.metrics import gaussian_inputs
from leeuwenhoek.models import load_argmedian

ROOT = Path(__file__).resolve().parents[1]
t0 = time.perf_counter()

_, w = load_argmedian(4, 3)
p = read_off(w)
design = designed_weights(p["a"], p["b"], p["e"], p["B2"], p["B3"], dtype=np.float64)

model_acc, _, _ = exact_accuracy(w)
design_acc, _, _ = exact_accuracy(design)
x = gaussian_inputs(1_000_000, 3, seed=12)
agreement = float(np.mean(forward(design, x).argmax(-1) == forward(w, x).argmax(-1)))

bs = [0.02, 0.05, 0.1, 0.2, 0.3, 0.5]
law = []
for bb in bs:
    acc, _, _ = exact_accuracy(designed_weights(p["a"], bb, p["e"], p["B2"], p["B3"], dtype=np.float64))
    law.append([bb / p["a"], 1 - acc])
gamma, logk = np.polyfit(np.log([r for r, _ in law]), np.log([e for _, e in law]), 1)

cones = mechanism_cones(w)
estimate = 1 - sum(error_of_cone(n, s) for n, s in cones.values())

commit = subprocess.run(["git", "rev-parse", "--short", "HEAD"], cwd=ROOT, capture_output=True, text=True).stdout.strip()
dirty = bool(subprocess.run(["git", "status", "--porcelain"], cwd=ROOT, capture_output=True, text=True).stdout.strip())

data = {
    "generated": datetime.now().strftime("%Y-%m-%d %H:%M"),
    "commit": commit + (" + cambios sin commit" if dirty else ""),
    "trained": {k: v.astype(np.float64).tolist() for k, v in w.items()},
    "design": p,
    "exact": {
        "model_accuracy": model_acc,
        "design_accuracy": design_acc,
        "design_agreement_1e6": agreement,
        "mechanism_estimate": estimate,
        "mechanism_cones": len(cones),
    },
    "law": {"points": law, "K": float(np.exp(logk)), "gamma": float(gamma)},
}
out = ROOT / "viz" / "data.js"
out.parent.mkdir(exist_ok=True)
out.write_text("// Generated by scripts/build_viz.py. Do not edit by hand.\nwindow.LEEUWENHOEK = "
               + json.dumps(data, indent=1) + ";\n")
print(f"wrote {out.relative_to(ROOT)} in {time.perf_counter() - t0:.1f} s (commit {data['commit']})")
